def color_at(x, y):
    # Deep navy-to-blue gradient with a subtle cyan glow.
    t = y / (H - 1)
    r = int(8 + 25 * t)
    g = int(24 + 31 * t)
    b = int(52 + 35 * t)
    if 210 < x < 1000 and 130 < y < 500:
        glow = max(0, 1 - abs(x - 600) / 430)
        r = min(255, r + int(20 * glow))
        g = min(255, g + int(40 * glow))
        b = min(255, b + int(42 * glow))
    return r, g, b

def draw_rect(x0, y0, x1, y1, color):
    for y in range(y0, y1):
        for x in range(x0, x1):
            pos = (y * W + x) * 3
            pixels[pos:pos + 3] = bytes(color)

def draw_text(text, x, y, scale, color):
    cursor = x
    for ch in text.upper():
        pattern = FONT.get(ch)
        if not pattern:
            cursor += 12 * scale
            continue
        for row, line in enumerate(pattern):
            for col, bit in enumerate(line):
                if bit == '1':
                    x0 = cursor + col * scale
                    y0 = y + row * scale
                    x1 = x0 + scale
                    y1 = y0 + scale
                    draw_rect(x0, y0, x1, y1, color)
        cursor += (max(map(len, FONT.values())) + 1) * scale

# Fill the canvas.
for y in range(H):
    for x in range(W):
        pixels.extend(color_at(x, y))

